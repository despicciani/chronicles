export function createBlankCampaign(params: {
  name: string;
  description: string;
  coverUrl?: string;
  gmName?: string;
  attributePointBudget?: number;
  maxTrainedSkills?: number;
}): CampaignState {
  const base = createStarterCampaign();
  const id = `camp-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
  const firstMapId = `map-${Date.now()}`;
  return {
    ...base,
    id,
    name: params.name.trim() || 'Nova Campanha de RPG',
    description: params.description.trim() || 'Uma nova aventura aguarda os heróis.',
    coverUrl: params.coverUrl || '',
    gmName: params.gmName?.trim() || 'Mestre',
    updatedAt: new Date().toISOString(),
    settings: {
      ...base.settings,
      attributePointBudget:
        typeof params.attributePointBudget === 'number' ? params.attributePointBudget : 15,
      maxTrainedSkills:
        typeof params.maxTrainedSkills === 'number' ? params.maxTrainedSkills : 4,
    },
    characters: [],
    maps: [
      {
        id: firstMapId,
        name: 'Mapa Principal da Aventura',
        mode: 'tactical',
        backgroundUrl: '',
        themePreset: 'castle',
        gridWidth: 22,
        gridHeight: 14,
        gridSizePx: 48,
        fogEnabled: false,
        revealedCells: [],
        weather: 'none',
        sceneNpcIds: [],
        tokens: [],
        templates: [],
      },
    ],
    activeMapId: firstMapId,
    combat: { active: false, round: 1, currentTurnIndex: 0, combatants: [] },
    rollLog: [
      {
        id: `log-${Date.now()}`,
        timestamp: new Date().toLocaleTimeString('pt-BR', { hour: '2-digit', minute: '2-digit' }),
        rollerName: 'Sistema',
        rollerRole: 'gm',
        title: 'Campanha Criada',
        formula: 'd20',
        individualRolls: ['20'],
        total: 20,
        isCrit: true,
        isSecret: false,
        details: `Campanha "${params.name}" iniciada por ${params.gmName || 'Mestre'}. Convide os jogadores para criarem seus personagens!`,
      },
    ],
    quests: [],
    npcs: [],
    gmNotes: [],
    customMusicTracks: [],
    activeBoss: null,
    groupTreasury: { gold: 0, items: [] },
  };
}

